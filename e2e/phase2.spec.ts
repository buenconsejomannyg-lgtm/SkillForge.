const key = "skillforge:workspace:v2";
async function load(page: Page, route: string) { await page.goto(route); await expect(page.getByRole("heading", { level: 1 })).toBeVisible(); }
async function editor(page: Page, button: Locator, title: string) { await button.click(); return page.getByRole("dialog", { name: title, exact: true }); }
async function save(dialog: Locator) { await dialog.getByRole("button", { name: "Save record", exact: true }).click(); await expect(dialog).toBeHidden(); }
async function state(page: Page) { return page.evaluate(key => JSON.parse(localStorage.getItem(key)!), key); }
