test("concurrent completion yields one reward and older-tab interference blocks new writes", async ({ page, context }) => {
    await load(page, "/learning");
    const other = await context.newPage();
    await load(other, "/learning");
    await other.evaluate(async()=>{await new Promise<void>(ready=>{void navigator.locks.request("skillforge:prototype:v1:write",()=>new Promise<void>(release=>{(window as unknown as {releaseCompletionLock:()=>void}).releaseCompletionLock=release;ready();}));});});
  await Promise.all([page.getByRole("checkbox", { name: /AI Basics and Capabilities/ }).check(), other.getByRole("checkbox", { name: /AI Basics and Capabilities/ }).check()]);
  await other.evaluate(()=>(window as unknown as {releaseCompletionLock:()=>void}).releaseCompletionLock());
    await expect.poll(async () => (await state(page)).rewards.length).toBe(1);
    const before = await page.evaluate(key => localStorage.getItem(key), key);
    await other.evaluate(() => localStorage.setItem("skillforge:prototype:v1", "old-tab-write"));
    await expect(page.getByRole("alert").filter({ hasText: "Storage needs attention" })).toBeVisible();
    await page.getByRole("checkbox", { name: /Prompt Engineering Fundamentals/ }).check();
    await expect(page.getByRole("alert").filter({ hasText: "Storage needs attention" })).toContainText("not saved");
    expect(await page.evaluate(key => localStorage.getItem(key), key)).toBe(before);
});
test("JSON backup export and reviewed restore preserve a recoverable previous workspace", async ({ page }) => {
    await load(page, "/dashboard");
    const backup = await state(page);
    const downloading = page.waitForEvent("download");
    await page.getByRole("button", { name: "Export workspace JSON", exact: true }).click();
    expect((await downloading).suggestedFilename()).toBe("skillforge-workspace-v2.json");
    await page.getByRole("checkbox", { name: /Explore context windows/ }).check();
    await expect.poll(async () => (await state(page)).rewards.length).toBe(1);
    await page.getByLabel("Choose workspace JSON to restore", { exact: true }).setInputFiles({ name: "backup.json", mimeType: "application/json", buffer: Buffer.from(JSON.stringify(backup)) });
    const dialog = page.getByRole("dialog", { name: "Replace this workspace?" });
    await expect(dialog).toContainText("0 XP");
    await dialog.getByRole("button", { name: "Confirm restore", exact: true }).click();
    await expect(dialog).toBeHidden();
    await expect(page.getByRole("checkbox", { name: /Explore context windows/ })).not.toBeChecked();
    expect(await page.evaluate(() => Object.keys(localStorage).some(k => k.startsWith("skillforge:restore-backup:")))).toBe(true);
});
